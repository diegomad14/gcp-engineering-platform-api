"""Service Factory — generates onboarding artifacts for new services.

Generates YAML contracts, caller workflow files, and checklists.
Does NOT create GCP resources, IAM bindings, or secrets.
"""

import textwrap
from typing import Optional

from ..config import config
from ..models import ServiceFactoryPlan, ServiceFactoryRequest, ServiceFactoryTemplate

_KNOWN_TEMPLATES = [
    ServiceFactoryTemplate(
        name="cloud-run-api",
        description="Cloud Run API service (Python FastAPI)",
        type="api",
    ),
    ServiceFactoryTemplate(
        name="cloud-run-web",
        description="Cloud Run Web service (React/Vite/nginx)",
        type="web",
    ),
    ServiceFactoryTemplate(
        name="cloud-run-worker",
        description="Cloud Run worker service (background processing)",
        type="worker",
    ),
    ServiceFactoryTemplate(
        name="cloud-run-integration",
        description="Cloud Run integration adapter (external API proxy)",
        type="integration",
    ),
]


def _build_yaml_contract(req: ServiceFactoryRequest) -> str:
    """Generate the gcp-application-release.yaml contract."""
    return textwrap.dedent(f"""\
    # Application release contract — generated by Engineering Platform Service Factory
    # Repo: diegomad14/gcp-engineering-platform

    application:
      name: {req.app_name}
      repository: <ORG>/{req.app_name}
      type: {req.service_type}

    release_target:
      platform: gcp-cloud-run
      services:
        api:
          service_name: {req.service_name}
          url: https://{req.service_name}-XXXXX-uc.a.run.app
          health_path: {req.health_path}
          openapi_path: {req.openapi_path}
          expected_openapi_paths: 1

    validation_targets:
      smoke_endpoints:{_format_validation_targets(req.validation_targets)}

    quality:
      sonarqube:
        enabled: true
        project_key: {req.sonar_project_key or '<ORG>_' + req.app_name}
        blocking_quality_gate: false

    security:
      workload_identity_provider: ${{{{ vars.GCP_WIF_PROVIDER }}}}
      deployer_service_account: ${{{{ vars.GCP_WIF_SERVICE_ACCOUNT }}}}
      forbidden:
        - GCP_SA_KEY
        - service_account_json
        - .env

    finops:
      labels:
        app: {req.app_name}
        env: {req.environment}
        owner: {req.owner}
        cost_center: {req.cost_center}
    """.replace("${{{{", "${{"))


def _format_validation_targets(targets: list[str]) -> str:
    if not targets:
        return " []"
    lines = []
    for t in targets:
        lines.append(f"      - name: {t}")
        lines.append("        path: /health")
        lines.append("        expected_status: 200")
        lines.append("        pii_safe: true")
        lines.append("        external_source: true")
    return "\n" + "\n".join(lines)


def _build_caller_workflow(
    workflow_name: str,
    platform_workflow: str,
    app_name: str,
    service_name: str,
    service_type: str,
) -> str:
    """Generate a caller workflow YAML."""
    return textwrap.dedent(f"""\
    # {workflow_name} — generated by Engineering Platform Service Factory
    # Calls: diegomad14/gcp-engineering-platform/.github/workflows/{platform_workflow}

    name: {workflow_name}

    on:
      workflow_dispatch:

    permissions:
      contents: read
      id-token: write

    jobs:
      call:
        uses: diegomad14/gcp-engineering-platform/.github/workflows/{platform_workflow}@v1
        with:
          project-id: ${{{{ vars.GCP_PROJECT_ID }}}}
          region: ${{{{ vars.GCP_REGION }}}}
          workload-identity-provider: ${{{{ vars.GCP_WIF_PROVIDER }}}}
          deployer-service-account: ${{{{ vars.GCP_WIF_SERVICE_ACCOUNT }}}}
          api-service-name: {service_name}
    """.replace("${{{{", "${{"))


def _build_sonar_properties(req: ServiceFactoryRequest) -> str:
    """Generate sonar-project.properties."""
    return textwrap.dedent(f"""\
    # SonarQube Cloud project configuration
    sonar.organization={req.sonar_organization or '<ORG>'}
    sonar.projectKey={req.sonar_project_key or f'{req.owner}_{req.app_name}'}
    sonar.projectName={req.app_name}
    sonar.sources=src
    sonar.sourceEncoding=UTF-8
    """)


def _build_labels_manifest(req: ServiceFactoryRequest) -> str:
    """Generate the Cloud Run labels manifest."""
    return textwrap.dedent(f"""\
    # Cloud Run Service Labels — generated by Engineering Platform Service Factory
    # Apply with:
    #   gcloud run services update {req.service_name} \\
    #     --project={req.gcp_project} \\
    #     --region={req.region} \\
    #     --update-labels=app={req.app_name},env={req.environment},owner={req.owner},cost_center={req.cost_center}

    labels:
      app: {req.app_name}
      env: {req.environment}
      owner: {req.owner}
      cost_center: {req.cost_center}
    """)


def _build_checklist(req: ServiceFactoryRequest) -> list[str]:
    """Generate an onboarding checklist."""
    return [
        f"Create GCP Cloud Run service: {req.service_name} in {req.gcp_project} ({req.region})",
        f"Apply labels: app={req.app_name}, env={req.environment}, owner={req.owner}, cost_center={req.cost_center}",
        "Create Artifact Registry repository (if not exists)",
        f"Create runtime service account: {req.service_name}-runtime@{req.gcp_project}.iam.gserviceaccount.com",
        f"Create deployer service account: {req.service_name}-deployer@{req.gcp_project}.iam.gserviceaccount.com",
        "Configure WIF/OIDC for deployer SA (see docs/standards/github-actions-wif.md)",
        f"Add SONAR_TOKEN to GitHub secrets (if SonarQube enabled)",
        "Add GCP_WIF_PROVIDER, GCP_WIF_SERVICE_ACCOUNT, GCP_PROJECT_ID, GCP_REGION to GitHub vars",
        "Copy generated caller workflows to .github/workflows/ in app repo",
        "Copy gcp-application-release.yaml to app repo",
        "Open PR with generated artifacts",
        "Complete platform adoption readiness checklist",
        "Schedule platform review",
    ]


def get_templates() -> list[ServiceFactoryTemplate]:
    return _KNOWN_TEMPLATES


def generate_plan(req: ServiceFactoryRequest) -> ServiceFactoryPlan:
    contract_yaml = _build_yaml_contract(req)
    service_name = req.service_name or req.app_name

    plan = ServiceFactoryPlan(
        app_name=req.app_name,
        service_name=service_name,
        generated_files=[
            f"{req.app_name}-release.yaml",
            "caller-pr-check.yml",
            "caller-release-candidate.yml",
            "caller-promote.yml",
            "caller-rollback.yml",
            "sonar-project.properties",
            "cloud-run-service-labels.yaml",
            "onboarding-checklist.md",
        ],
        checklist=_build_checklist(req),
        yaml_contract=contract_yaml,
        caller_pr_check=_build_caller_workflow(
            f"{req.app_name} PR Check",
            "reusable-pr-check.yml",
            req.app_name,
            service_name,
            req.service_type,
        ),
        caller_release_candidate=_build_caller_workflow(
            f"{req.app_name} Release Candidate",
            "reusable-cloud-run-release-candidate.yml",
            req.app_name,
            service_name,
            req.service_type,
        ),
        caller_promote=_build_caller_workflow(
            f"{req.app_name} Promote",
            "reusable-cloud-run-promote.yml",
            req.app_name,
            service_name,
            req.service_type,
        ),
        caller_rollback=_build_caller_workflow(
            f"{req.app_name} Rollback",
            "reusable-cloud-run-rollback.yml",
            req.app_name,
            service_name,
            req.service_type,
        ),
        labels_manifest=_build_labels_manifest(req),
        sonar_properties=_build_sonar_properties(req),
    )

    return plan
