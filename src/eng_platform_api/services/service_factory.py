def _build_platform_rollback_workflow() -> str:
    return (_REPO_ROOT / ".github" / "workflows" / "platform-rollback.yml").read_text()


def _build_semantic_release_workflow(service_name: str = "") -> str:
    workflow = textwrap.dedent("""\
    name: Semantic Release

    on:
      push:
        branches: [main]

    permissions:
      contents: write
      issues: write
      pull-requests: write

    concurrency:
      group: semantic-release
      cancel-in-progress: false

    jobs:
      release:
        runs-on: ubuntu-latest
        steps:
          - uses: actions/checkout@34e114876b0b11c390a56381ad16ebd13914f8d5 # v4
            with:
              fetch-depth: 0
          - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4
            with:
              node-version: "22"
          - name: Create semantic version tag and GitHub release
            env:
              GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
            run: >-
              npx --yes
              --package semantic-release@25.0.7
              --package @semantic-release/commit-analyzer@13.0.1
              --package @semantic-release/release-notes-generator@14.1.1
              --package @semantic-release/github@12.0.9
              semantic-release
    """)

    gate = f"""      - name: Require exact OSS quality evidence
        uses: diegomad14/gcp-engineering-platform-api/.github/actions/verify-quality@ac9d68554c8b6332013785a5bcf451eabfee93ec
        with:
          platform-api-url: ${{{{ vars.ENG_PLATFORM_API_URL }}}}
          service-name: {service_name}
          commit-sha: ${{{{ github.sha }}}}
          wait-seconds: '1800'
"""
    workflow = workflow.replace("${{{{", "${{").replace("}}}}", "}}")
    return workflow.replace(
        "      - name: Create semantic version",
        gate + "      - name: Create semantic version",
    )


def _build_agent_prompt(req: ServiceFactoryRequest) -> str:
    if req.runtime_kind == "cloud_run_job":
        release_instructions = (
            "- This is a Cloud Run Job proposal. Deployment remains disabled.\n"
            "- Review the Cloud Run Job executor, quality evidence and job-specific release policy before enabling deployment.\n"
            "- Do not install Service deploy/promote/rollback workflows or HTTP health checks for this Job.\n"
        )
    else:
        release_instructions = (
            "- After review and merge, wait for semantic-release to create a vX.Y.Z tag.\n"
            f"- Use the reviewed platform release process for {req.service_name}; preserve the same SHA/tag.\n"
        )
    return (
        f"Prepare Engineering Platform adoption for {req.service_name} in {req.repository}.\n\n"
        "These are local proposals, not evidence of a created or deployed resource.\n"
        "- Review generated artifacts before preparing a PR.\n"
        "- Validate with actionlint and the repository's normal test/build commands.\n"
        "- Preserve protected checks, existing deployment authorization and triggers.\n"
        "- Do not commit secrets, .env, service account JSON, tokens, or customer data.\n"
        f"- From the API repository, validate with: python scripts/catalog_registry.py --check catalog/services/{req.service_name}.yaml\n"
        "- Only after review, rerun with --write to update the runtime JSON catalog.\n"
        "- Registration keeps logs disabled and the reader list empty; a separate reviewed policy change is required for access.\n"
        + release_instructions
        + "Never use GCP Console, gcloud run deploy, gcloud run jobs deploy, traffic updates, or direct workflow dispatch for an unapproved production change.\n"
    )


def _build_labels_manifest(req: ServiceFactoryRequest) -> str:
    """Describe desired labels without applying changes to either resource kind."""
    return (
        f"# {req.runtime_kind} label proposal; review before applying.\n"
        "# No Cloud Run resources, IAM or labels have been changed.\n"
        + yaml.safe_dump({"labels": _labels(req)}, sort_keys=False)
    )


def _build_checklist(req: ServiceFactoryRequest) -> list[str]:
    """Close the proposal-to-runtime-catalog gap explicitly."""
    kind = "Job" if req.runtime_kind == "cloud_run_job" else "Service"
    steps = [
        f"Confirm Cloud Run {kind} identity and existence separately: {req.service_name} in {req.gcp_project} ({req.region}); this plan created no resource",
        "Reserve service_name globally: duplicates across projects, regions or runtime kinds are rejected",
        "Review owner, repository, project_id, region, runtime_kind, quality policy and proposed labels",
        "Confirm Artifact Registry, runtime accounts and deployment authorization through the approved platform process",
        "Review generated CI/quality and semantic-release proposals before copying them to the resource repository",
        f"Review {'gcp-job-release.yaml' if kind == 'Job' else 'gcp-service-release.yaml'}; it does not register or create a resource",
        f"From the API repository run: python scripts/catalog_registry.py --check catalog/services/{req.service_name}.yaml",
        f"After review run: python scripts/catalog_registry.py --write catalog/services/{req.service_name}.yaml",
        "Review the diff of src/eng_platform_api/static_examples/mock_catalog.json, the actual shared source; catalog/services/*.yaml is not loaded at runtime",
        "Verify the new resource in /api/catalog/services after the reviewed catalog is delivered through the normal release process",
        "Keep logs.enabled=false and logs.allowed_logins=[]; approve any log readers in a separate catalog policy review",
    ]
    if kind == "Job":
        steps.append(
            "Keep deployment.enabled=false until the Cloud Run Job executor and job-specific release policy have been reviewed; no Service deploy/promote/rollback workflows or HTTP contract are generated"
        )
    else:
        steps.append(
            "Review proposed platform-deploy.yml and platform-rollback.yml; after approved adoption use the platform release process with the exact qualified SHA/tag"
        )
    return steps


def get_templates() -> list[ServiceFactoryTemplate]:
    return _KNOWN_TEMPLATES


def generate_plan(req: ServiceFactoryRequest) -> ServiceFactoryPlan:
    from . import log_catalog
    from fastapi import HTTPException

    # A draft must not silently turn a known inventory-only resource into a
    # deployment target. Its adoption requires a separately reviewed metadata change.
    existing = next(
        (
            item
            for item in log_catalog.load_catalog()
            if item["service_name"] == req.service_name
        ),
        None,
    )
    if existing and existing.get("management_mode") == "observability_only":
        raise HTTPException(
            status_code=409,
            detail="Observation-only resource cannot use managed operations",
        )
    contract_yaml = _build_yaml_contract(req)
    service_name = req.service_name
    is_job = req.runtime_kind == "cloud_run_job"

    plan = ServiceFactoryPlan(
        repository=req.repository,
        service_name=service_name,
        generated_files=[
            "gcp-job-release.yaml" if is_job else "gcp-service-release.yaml",
            ".github/workflows/ci.yml",
            *(
                []
                if is_job
                else [
                    ".github/workflows/platform-deploy.yml",
                    ".github/workflows/platform-rollback.yml",
                ]
            ),
            ".github/workflows/semantic-release.yml",
            f"catalog/services/{service_name}.yaml",
            ".quality-gate.yml",
            f"{req.quality_working_directory.rstrip('/')}/.quality-sources.json",
            "cloud-run-job-labels.yaml" if is_job else "cloud-run-service-labels.yaml",
            "onboarding-checklist.md",
            "agent-handoff-prompt.md",
        ],
        checklist=_build_checklist(req),
        yaml_contract=contract_yaml,
        caller_pr_check=_build_caller_workflow(
            f"{req.service_name} PR Check",
            "reusable-pr-check.yml",
            service_name,
            req.service_type,
            req.quality_profile or req.runtime,
            req.quality_working_directory,
            req.coverage_threshold,
        ),
        caller_release_candidate=""
        if is_job
        else _build_caller_workflow(
            f"{req.service_name} Release Candidate",
            "reusable-cloud-run-release-candidate.yml",
            service_name,
            req.service_type,
            req.quality_profile or req.runtime,
            req.quality_working_directory,
            req.coverage_threshold,
        ),
        caller_promote=""
        if is_job
        else _build_caller_workflow(
            f"{req.service_name} Promote",
            "reusable-cloud-run-promote.yml",
            service_name,
            req.service_type,
            req.quality_profile or req.runtime,
            req.quality_working_directory,
            req.coverage_threshold,
        ),
        caller_rollback=""
        if is_job
        else _build_caller_workflow(
            f"{req.service_name} Rollback",
            "reusable-cloud-run-rollback.yml",
            service_name,
            req.service_type,
            req.quality_profile or req.runtime,
            req.quality_working_directory,
            req.coverage_threshold,
        ),
        platform_deploy_workflow="" if is_job else _build_platform_deploy_workflow(),
        platform_rollback_workflow=""
        if is_job
        else _build_platform_rollback_workflow(),
        semantic_release_workflow=_build_semantic_release_workflow(req.service_name),
        catalog_entry=_build_catalog_entry(req),
        agent_prompt=_build_agent_prompt(req),
        labels_manifest=_build_labels_manifest(req),
        quality_config=_build_quality_config(req),
        quality_sources=json.dumps(
            {
                "roots": ["src"],
                "exclude": ["**/*.test.ts", "**/*.test.tsx", "src/test/*", "**/*.d.ts"]
                if (req.quality_profile or req.runtime) == "node"
                else [],
            },
            indent=2,
        ),
        sonar_properties="",
    )

    return plan
