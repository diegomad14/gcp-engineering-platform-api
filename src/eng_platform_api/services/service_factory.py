def _build_yaml_contract(req: ServiceFactoryRequest) -> str:
    """Generate a proposal, with HTTP release semantics only for Services."""
    is_job = req.runtime_kind == "cloud_run_job"
    target: dict[str, object] = {
        "platform": "gcp-cloud-run",
        "runtime_kind": req.runtime_kind,
        "service_name": req.service_name,
        "project_id": req.gcp_project,
        "region": req.region,
    }
    if not is_job:
        target.update(
            url=f"https://{req.service_name}-XXXXX-uc.a.run.app",
            health_path=req.health_path,
            openapi_path=req.openapi_path,
            expected_openapi_paths=1,
        )
    contract: dict[str, object] = {
        "service": {
            "name": req.service_name,
            "repository": req.repository,
            "type": req.service_type,
        },
        "release_target": target,
        "quality": {
            "quality_gate": {
                "enabled": True,
                "profile": req.quality_profile or req.runtime,
                "working_directory": req.quality_working_directory,
                "coverage_threshold": req.coverage_threshold,
                "policy_version": "oss-v2",
                "differential_threshold": 80,
                "blocking": True,
            }
        },
        "security": {
            "workload_identity_provider": "${{ vars.GCP_WIF_PROVIDER }}",
            "deployer_service_account": "${{ vars.GCP_WIF_SERVICE_ACCOUNT }}",
            "forbidden": ["GCP_SA_KEY", "service_account_json", ".env"],
        },
        "finops": {"labels": _labels(req)},
    }
    if is_job:
        contract["deployment"] = {
            "enabled": False,
            "executor": "cloud_build",
            "review_required": "Review the Cloud Run Job executor and job-specific release policy before enabling deployment.",
        }
    else:
        contract["validation_targets"] = {
            "smoke_endpoints": [
                {
                    "name": name,
                    "path": "/health",
                    "expected_status": 200,
                    "pii_safe": True,
                    "external_source": True,
                }
                for name in req.validation_targets
                if name.strip()
            ]
        }
    return (
        "# Release contract proposal; no Cloud Run resource has been created.\n"
        f"# Repo: {req.repository}\n" + yaml.safe_dump(contract, sort_keys=False)
    )


def _build_caller_workflow(
    workflow_name: str,
    platform_workflow: str,
    service_name: str,
    service_type: str,
    quality_profile: str,
    quality_working_directory: str,
    coverage_threshold: float,
) -> str:
    """Generate a caller workflow YAML."""
    if platform_workflow == "reusable-pr-check.yml":
        return textwrap.dedent(
            f"""\
        # {workflow_name} — generated by Engineering Platform Service Factory
        name: {workflow_name}

        on:
          pull_request:
            branches: [main]
          push:
            branches: [main]

        permissions:
          contents: read

        jobs:
          quality:
            uses: diegomad14/gcp-engineering-platform-api/.github/workflows/reusable-quality-gate.yml@bac46b1a70c0305470ed1d4c11a18bf07c09ab76
            with:
              service-name: {service_name}
              profile: {quality_profile}
              working-directory: {quality_working_directory}
              coverage-threshold: {coverage_threshold}
              platform-ref: bac46b1a70c0305470ed1d4c11a18bf07c09ab76
              platform-api-url: ${{{{ vars.ENG_PLATFORM_API_URL }}}}
            secrets:
              QUALITY_API_TOKEN: ${{{{ secrets.QUALITY_API_TOKEN }}}}
        """.replace("${{{{", "${{")
        )

    dispatch = "workflow_dispatch:"
    quality_sha_value = "${{ github.sha }}"
    if platform_workflow in {
        "reusable-cloud-run-promote.yml",
        "reusable-cloud-run-rollback.yml",
    }:
        dispatch = textwrap.dedent("""\
        workflow_dispatch:
          inputs:
            quality_commit_sha:
              description: Commit SHA approved by the quality gate
              required: true
              type: string
        """).rstrip()
        quality_sha_value = "${{ inputs.quality_commit_sha }}"
    header = textwrap.dedent(f"""\
    # {workflow_name} — generated by Engineering Platform Service Factory
    # Calls: diegomad14/gcp-engineering-platform-api/.github/workflows/{platform_workflow}

    name: {workflow_name}

    on:
    """)
    body = textwrap.dedent(
        f"""\
    permissions:
      contents: read
      id-token: write

    jobs:
      call:
        uses: diegomad14/gcp-engineering-platform-api/.github/workflows/{platform_workflow}@bac46b1a70c0305470ed1d4c11a18bf07c09ab76
        with:
          project-id: ${{{{ vars.GCP_PROJECT_ID }}}}
          region: ${{{{ vars.GCP_REGION }}}}
          workload-identity-provider: ${{{{ vars.GCP_WIF_PROVIDER }}}}
          deployer-service-account: ${{{{ vars.GCP_WIF_SERVICE_ACCOUNT }}}}
          api-service-name: {service_name}
          platform-api-url: ${{{{ vars.ENG_PLATFORM_API_URL }}}}
          quality-gate-enabled: true
          quality-commit-sha: {quality_sha_value.replace("${{", "${{{{")}
        secrets:
          QUALITY_API_TOKEN: ${{{{ secrets.QUALITY_API_TOKEN }}}}
    """.replace("${{{{", "${{")
    )
    return header + textwrap.indent(dispatch, "  ") + "\n\n" + body


def _build_quality_config(req: ServiceFactoryRequest) -> str:
    """Generate the repository-owned quality gate configuration."""
    return textwrap.dedent(f"""\
    # Open source quality gate — consumed by reusable-quality-gate.yml
    service_name: {req.service_name}
    profile: {req.quality_profile or req.runtime}
    working_directory: {req.quality_working_directory}
    coverage_threshold: {req.coverage_threshold}
    policy_version: oss-v2
    differential_threshold: 80
    blocking:
      lint: true
      tests: true
      build: true
      sast_severities: [ERROR]
      dependency_severities: [HIGH, CRITICAL]
      secrets: true
    """)


def _labels(req: ServiceFactoryRequest) -> dict[str, str]:
    return {
        "service": req.service_name,
        "env": req.environment,
        "owner": req.owner,
        "cost_center": req.cost_center,
    }


def _build_catalog_entry(req: ServiceFactoryRequest) -> str:
    """A registration proposal never grants log access."""
    is_job = req.runtime_kind == "cloud_run_job"
    deployment: dict[str, object] = {
        "enabled": not is_job,
        "runtime_kind": req.runtime_kind,
        "executor": "cloud_build" if is_job else "auto",
        "image_name": req.cloud_run_service_name or req.service_name,
        "artifact_repository": "cgm-sanplat-repo",
        "build_context": req.quality_working_directory,
        "dockerfile_path": (
            "Dockerfile"
            if req.quality_working_directory == "."
            else f"{req.quality_working_directory}/Dockerfile"
        ),
        "health_path": "" if is_job else req.health_path,
    }
    if not is_job:
        deployment["workflow_file"] = "platform-deploy.yml"
    entry = {
        "management_mode": "managed",
        "service_name": req.service_name,
        "repository": req.repository,
        "owner": req.owner,
        "cost_center": req.cost_center,
        "project_id": req.gcp_project,
        "region": req.region,
        "environment": req.environment,
        "release_model": "managed-release" if is_job else "candidate-promote-rollback",
        "release_policy": "oss-v2",
        "quality": {
            "enabled": True,
            "profile": req.quality_profile or req.runtime,
            "coverage_threshold": req.coverage_threshold,
            "policy_version": "oss-v2",
            "differential_threshold": 80,
        },
        "deployment": deployment,
        "logs": {"enabled": False, "allowed_logins": []},
        "finops": _labels(req),
    }
    return yaml.safe_dump(entry, sort_keys=False)


